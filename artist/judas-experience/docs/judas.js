  /* ---------- Web Audio — Motor del barco ---------- */
  const AudioEngine = {
    ctx: null, master: null, running: false, nodes: [],
    init() {
      if (this.ctx) return;
      this.ctx = new (window.AudioContext || window.webkitAudioContext)();
      this.master = this.ctx.createGain();
      this.master.gain.value = 0;
      this.master.connect(this.ctx.destination);
      this.buildPad(); this.buildPulse();
    },
    filter(freq, type, q) {
      const f = this.ctx.createBiquadFilter();
      f.frequency.value = freq; f.type = type; f.Q.value = q || 1;
      return f;
    },
    buildPad() {
      const g = this.ctx.createGain(); g.gain.value = 0.05;
      const lp = this.filter(220, "lowpass", 0.8);
      [55, 110, 164.81, 220].forEach((freq, i) => {
        const o1 = this.ctx.createOscillator(); o1.type = "sawtooth"; o1.frequency.value = freq; o1.detune.value = -6;
        const o2 = this.ctx.createOscillator(); o2.type = "sawtooth"; o2.frequency.value = freq; o2.detune.value = 6;
        const og = this.ctx.createGain(); og.gain.value = 0.22 / (i + 1);
        o1.connect(og); o2.connect(og); og.connect(lp);
        o1.start(); o2.start();
        this.nodes.push(o1, o2);
      });
      lp.connect(g); g.connect(this.master);
      this.padGain = g;
    },
    buildPulse() {
      const g = this.ctx.createGain(); g.gain.value = 0.0;
      const lp = this.filter(160, "lowpass", 1);
      const o = this.ctx.createOscillator(); o.type = "sine"; o.frequency.value = 48;
      o.connect(lp); lp.connect(g); g.connect(this.master);
      o.start();
      this.pulseGain = g;
      this.pulseOsc = o;
      this.pulseLP = lp;
    },
    start() {
      this.init();
      if (this.running) return;
      this.ctx.resume();
      this.running = true;
      const now = this.ctx.currentTime;
      this.master.gain.cancelScheduledValues(now);
      this.master.gain.setValueAtTime(0, now);
      this.master.gain.linearRampToValueAtTime(0.8, now + 1.2);
      this.beat = this.ctx.currentTime;
      this.scheduleBeats();
      this.vizRunning = true;
      this.drawViz();
    },
    scheduleBeats() {
      if (!this.running) return;
      const interval = 60 / 96;
      const now = this.ctx.currentTime;
      while (this.beat < now + 0.25) {
        const t0 = this.beat;
        this.pulseGain.gain.cancelScheduledValues(t0);
        this.pulseGain.gain.setValueAtTime(0.55, t0);
        this.pulseGain.gain.exponentialRampToValueAtTime(0.02, t0 + 0.22);
        this.pulseLP.frequency.setValueAtTime(90, t0);
        this.pulseLP.frequency.exponentialRampToValueAtTime(320, t0 + 0.22);
        this.beat += interval;
      }
      this.timer = setTimeout(() => this.scheduleBeats(), 120);
    },
    stop() {
      if (!this.ctx || !this.running) return;
      this.running = false;
      clearTimeout(this.timer);
      const now = this.ctx.currentTime;
      this.master.gain.cancelScheduledValues(now);
      this.master.gain.setValueAtTime(this.master.gain.value, now);
      this.master.gain.linearRampToValueAtTime(0, now + 0.8);
    },
    setVolume(v) {
      if (!this.ctx) return;
      this.vol = v;
      if (this.running) this.master.gain.value = 0.8 * v;
    },
    drawViz() {
      if (!this.vizRunning) return;
      requestAnimationFrame(() => this.drawViz());
      const cv = $("#viz"); if (!cv) return;
      const ctx = cv.getContext("2d");
      const W = cv.width, H = cv.height;
      ctx.clearRect(0, 0, W, H);
      const analyser = new Uint8Array(0);
      const bars = 48, bw = W / bars;
      const t = performance.now() / 1000;
      for (let i = 0; i < bars; i++) {
        const phase = Math.sin(t * 2.1 + i * 0.42) * 0.5 + 0.5;
        const pulse = this.running ? Math.max(0, Math.sin((t * 96 / 60) * Math.PI * 2) * 0.5 + 0.5) : 0.2;
        const h = (phase * 0.55 + pulse * 0.45) * H * 0.86 + 8;
        const grd = ctx.createLinearGradient(0, H - h, 0, H);
        grd.addColorStop(0, "#ff1e4d"); grd.addColorStop(0.6, "#d90429"); grd.addColorStop(1, "#4a0713");
        ctx.fillStyle = grd;
        ctx.fillRect(i * bw + 2, H - h, bw - 4, h);
      }
    }
  };

